#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────────────────
# 팀핑 플러그인 — Stop 훅. 자동화 세기 lv3(적극)에서만 "기록했나?" 리마인더를 남긴다.
#   lv0·lv1·lv2 → 조용(exit 0)
#   lv3         → 짧은 리마인더 1줄
#
# Stop 훅은 매 턴 끝에 실행된다. 어떤 경우에도 세션을 막지 않는다(출력 한 줄 · exit 0).
# ─────────────────────────────────────────────────────────────────────────────
set -uo pipefail

# 자동화 세기(TEAMPING_LEVEL) 해석:
#   · lv0~lv3 이면 그대로
#   · 플러그인으로 실행 중인데(CLAUDE_PLUGIN_ROOT 있음) 값이 비었거나 치환되지 않은 템플릿이면 → 기본값 lv2
#     (CLI 로 설치하면 옵션을 묻지 않아 값이 비어 있을 수 있다)
#   · 플러그인이 아니면(훅을 직접 건 경우) → lv1 — 지정하지 않은 자동화는 켜지 않는다
LEVEL="${TEAMPING_LEVEL-}"
case "$LEVEL" in
  lv0 | lv1 | lv2 | lv3) ;;
  *) [ -n "${CLAUDE_PLUGIN_ROOT:-}" ] && LEVEL="lv2" || LEVEL="lv1" ;;
esac
[ "$LEVEL" = "lv3" ] || exit 0

echo "🏓 팀핑 기록 확인 — 작업이 끝났다면 submit_manifest로 남겼는지 보세요(커밋 전 조율 = 팀핑을 쓰는 이유)."
exit 0
